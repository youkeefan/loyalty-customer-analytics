-- 1. Create dedicated warehouse
CREATE WAREHOUSE IF NOT EXISTS LOYALTY_WH
WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

-- 2. Create project database
CREATE DATABASE IF NOT EXISTS LOYALTY_DB;

-- 3. Create project schemas
CREATE SCHEMA IF NOT EXISTS LOYALTY_DB.RAW;

CREATE SCHEMA IF NOT EXISTS LOYALTY_DB.ANALYTICS;

-- 4. Set project context
USE WAREHOUSE LOYALTY_WH;
USE DATABASE LOYALTY_DB;
USE SCHEMA RAW;

CREATE TABLE CUSTOMERS (
    CUSTOMER_ID VARCHAR(20),
    SIGNUP_DATE DATE,
    LOYALTY_TIER VARCHAR(20),
    CUSTOMER_STATUS VARCHAR(20)
);

CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    TRANSACTION_DATE DATE,
    SPEND NUMBER(10,2),
    POINTS_EARNED NUMBER(10,0)
);

CREATE TABLE POINTS_LEDGER (
    LEDGER_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    TRANSACTION_ID VARCHAR(20),
    ACTIVITY_DATE DATE,
    ACTIVITY_TYPE VARCHAR(20),
    POINTS_CHANGE NUMBER(10,0)
);

CREATE STAGE LOYALTY_DB.RAW.LOYALTY_STAGE;

SHOW STAGES IN SCHEMA LOYALTY_DB.RAW;


LIST @LOYALTY_DB.RAW.LOYALTY_STAGE;

CREATE FILE FORMAT LOYALTY_DB.RAW.LOYALTY_CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE;

SHOW FILE FORMATS IN SCHEMA LOYALTY_DB.RAW;

--customer data
COPY INTO LOYALTY_DB.RAW.CUSTOMERS
FROM @LOYALTY_DB.RAW.LOYALTY_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'LOYALTY_DB.RAW.LOYALTY_CSV_FORMAT'
)
PATTERN = '.*customers[.]csv'
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*)
FROM LOYALTY_DB.RAW.CUSTOMERS;

---transactions data
COPY INTO LOYALTY_DB.RAW.TRANSACTIONS
FROM @LOYALTY_DB.RAW.LOYALTY_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'LOYALTY_DB.RAW.LOYALTY_CSV_FORMAT'
)
PATTERN = '.*transactions[.]csv'
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_TRANSACTIONS
FROM LOYALTY_DB.RAW.TRANSACTIONS;

---points data
COPY INTO LOYALTY_DB.RAW.POINTS_LEDGER
FROM @LOYALTY_DB.RAW.LOYALTY_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'LOYALTY_DB.RAW.LOYALTY_CSV_FORMAT'
)
PATTERN = '.*points_ledger[.]csv'
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_LEDGER_RECORDS
FROM LOYALTY_DB.RAW.POINTS_LEDGER;

