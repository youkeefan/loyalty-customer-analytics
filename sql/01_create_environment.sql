SELECT 'CUSTOMERS' AS TABLE_NAME,
       COUNT(*) AS TOTAL_RECORDS
FROM LOYALTY_DB.RAW.CUSTOMERS

UNION ALL

SELECT 'TRANSACTIONS',
       COUNT(*)
FROM LOYALTY_DB.RAW.TRANSACTIONS

UNION ALL

SELECT 'POINTS_LEDGER',
       COUNT(*)
FROM LOYALTY_DB.RAW.POINTS_LEDGER;